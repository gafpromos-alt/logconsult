# ---------------------------------------------------------------------------
def normaliza(item, ln):
    """Converte a tupla bruta (formato depende do tipo) para o formato de insercao:
    (data_cad, vi, vf, tr, tarifa, frete_total, frete_fca, frete_efvm, mo, md, dp)
    """
    tipo = FLUXOS[item]["tipo"]
    if tipo == "EFC_SIMPLES":
        data_cad, vi, vf, tr, tarifa, frete, mo, md = ln
        return (data_cad, vi, vf, tr, tarifa, frete, None, None, mo, md, None)
    if tipo == "FCA_EFVM":
        data_cad, vi, vf, tr, tarifa, frete_fca, frete_efvm, mo, md = ln
        frete_total = round(frete_fca + frete_efvm, 2)
        return (data_cad, vi, vf, tr, tarifa, frete_total, frete_fca, frete_efvm, mo, md, None)
    if tipo == "FNS_DP":
        data_cad, vi, vf, tr, tarifa, frete, mo, md, dp = ln
        return (data_cad, vi, vf, tr, tarifa, frete, None, None, mo, md, dp)
    if tipo == "FNS_DP_NOMO":
        data_cad, vi, vf, tr, tarifa, frete, md, dp = ln
        return (data_cad, vi, vf, tr, tarifa, frete, None, None, None, md, dp)
    raise ValueError(f"tipo desconhecido: {tipo}")


def validar(dados):
    """frete_total + (mo ou 0) + (md ou 0) + (dp ou 0) == tarifa_contrato (tolerancia 0,05)."""
    problemas = []
    for item, linhas in dados.items():
        for ln in linhas:
            (data_cad, vi, vf, tr, tarifa, frete, frete_fca, frete_efvm,
             mo, md, dp) = normaliza(item, ln)
            soma = (frete or 0) + (mo or 0) + (md or 0) + (dp or 0)
            if abs(soma - tarifa) > 0.05:
                problemas.append(
                    f"item {item} vig {vi} (cad {data_cad}): soma servicos {soma:.2f} "
                    f"!= tarifa_contrato {tarifa:.2f}"
                )
    return problemas


